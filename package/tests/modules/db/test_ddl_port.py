def test_add_foreign_key_constraint_takes_referential_action_enums(sql_dialect: SQLDialect, mock_db) -> None:
    q = AlterTableQuery(sql_dialect, "posts", database=mock_db)
    q.add_foreign_key_constraint(
        "user_id",
        "users",
        "id",
        name="fk1",
        on_delete=ReferentialActionEnum.CASCADE,
        on_update=ReferentialActionEnum.SET_NULL,
    )

    alter = q._alters[0]
    assert isinstance(alter, AddForeignKeyConstraint)
    assert alter.on_delete == "CASCADE"
    assert alter.on_update == "SET NULL"


def test_foreign_key_constraint_emits_referential_actions_in_create_table(sql_dialect: SQLDialect, mock_db) -> None:
    q = CreateTableQuery(sql_dialect, "posts", database=mock_db)
    q.integer("id")
    q.foreign_key_constraint(
        "user_id",
        "users",
        "id",
        name="fk1",
        on_delete=ReferentialActionEnum.CASCADE,
        on_update=ReferentialActionEnum.SET_NULL,
    )
    sql = q.to_query_with_params().query

    assert "ON DELETE CASCADE" in sql
    assert "ON UPDATE SET NULL" in sql


def test_foreign_key_constraint_takes_composite_columns(sql_dialect: SQLDialect, mock_db) -> None:
    """Lists of columns pair up positionally with the referenced columns."""
    q = CreateTableQuery(sql_dialect, "order_lines", database=mock_db)
    q.integer("order_id")
    q.integer("user_id")
    q.foreign_key_constraint(["order_id", "user_id"], "orders", ["id", "user_id"])
    sql = q.to_query_with_params().query

    assert 'FOREIGN KEY ("order_id", "user_id") REFERENCES "orders" ("id", "user_id")' in sql


