def test_create_table_builders_produce_column_dataclass_instances(sql_dialect: SQLDialect, mock_db) -> None:
    """Every ColumnsDefinitionMixin builder method must append a `Column`
    dataclass to `_columns`, not an untyped dict -- this is the crux of the
    dict-to-dataclass migration."""
    q = CreateTableQuery(sql_dialect, "widgets", database=mock_db)
    q.integer("id")
    q.string("name")
    q.boolean("active")
    q.identity("pk")

    assert all(isinstance(col, Column) for col in q._columns)


def test_create_table_constraint_builders_produce_constraint_dataclass_instances(
    sql_dialect: SQLDialect, mock_db
) -> None:
    """unique_constraint()/foreign_key_constraint()/constraint() must append
    ConstraintABC dataclasses, discriminated by class rather than a "type"
    string key."""
    q = CreateTableQuery(sql_dialect, "widgets", database=mock_db)
    q.unique_constraint(["name"])
    q.foreign_key_constraint("owner_id", "users", "id")
    q.constraint("CHECK (id > 0)")

    assert isinstance(q._constraints[0], UniqueConstraint)
    assert isinstance(q._constraints[1], ForeignKeyConstraint)
    assert isinstance(q._constraints[2], RawConstraint)
    assert all(isinstance(c, ConstraintABC) for c in q._constraints)


def test_alter_table_builders_produce_alter_dataclass_instances(sql_dialect: SQLDialect, mock_db) -> None:
    """Every AltersMixin builder method must append the matching AlterABC
    dataclass -- add_column -> AddColumn, alter_column -> AlterColumn,
    rename_column -> RenameColumn, drop_column -> DropColumn,
    add_primary_keys -> AddPrimaryKeys, add_unique_constraint ->
    AddUniqueConstraint, add_foreign_key_constraint ->
    AddForeignKeyConstraint, drop_constraint -> DropConstraint,
    alter -> RawAlter."""
    q = AlterTableQuery(sql_dialect, "widgets", database=mock_db)
    q.add_column("email", TypeEnum.STRING)
    q.alter_column("age", "TYPE BIGINT")
    q.rename_column("old", "new")
    q.drop_column("temp")
    q.add_primary_keys("id")
    q.add_unique_constraint(["email"])
    q.add_foreign_key_constraint("owner_id", "users", "id")
    q.drop_constraint("uq_email")
    q.alter("SOME RAW SQL")

    expected_types = [
        AddColumn,
        AlterColumn,
        RenameColumn,
        DropColumn,
        AddPrimaryKeys,
        AddUniqueConstraint,
        AddForeignKeyConstraint,
        DropConstraint,
        RawAlter,
    ]
    assert [type(alter) for alter in q._alters] == expected_types
    assert all(isinstance(alter, AlterABC) for alter in q._alters)


def test_unknown_alter_type_raises_clear_error(sql_dialect: SQLDialect) -> None:
    """An AlterABC subtype the dialect doesn't recognize must raise a clear
    QueryError from `_build_alter`, not silently render a bare
    'ALTER TABLE t' with the operation dropped."""

    @dataclass
    class _UnknownAlter(AlterABC):
        pass

    with pytest.raises(QueryError, match="Unsupported alter type"):
        sql_dialect.alter_table(table="t", alters=[_UnknownAlter()])


def test_unknown_constraint_type_raises_clear_error(sql_dialect: SQLDialect) -> None:
    """A ConstraintABC subtype the dialect doesn't recognize must raise a
    clear QueryError from `_build_constraint`, not silently emit an empty
    constraint clause."""

    @dataclass
    class _UnknownConstraint(ConstraintABC):
        pass

    with pytest.raises(QueryError, match="Unsupported constraint type"):
        sql_dialect.create_table(
            if_not_exists=False,
            table="t",
            columns=[Column(name="id", type=TypeEnum.INT)],
            primary_keys=None,
            constraints=[_UnknownConstraint()],
        )
