def test_sqlite_unique_constraint_strips_name(sqlite_dialect: SQLiteDialect) -> None:
    """SQLiteDialect::buildUniqueConstraint/buildForeignKeyConstraint always
    strip the constraint name before delegating to the shared builder."""
    sql = sqlite_dialect._build_constraint(UniqueConstraint(columns=["email"], name="uq_email"))
    assert sql == 'UNIQUE ("email")'


def test_sqlite_foreign_key_constraint_strips_name(sqlite_dialect: SQLiteDialect) -> None:
    sql = sqlite_dialect._build_constraint(
        ForeignKeyConstraint(
            columns=["user_id"],
            ref_table="users",
            ref_columns=["id"],
            name="fk_user",
        )
    )
    assert sql == 'FOREIGN KEY ("user_id") REFERENCES "users" ("id")'


def test_sqlite_create_table_excludes_auto_increment_column_from_primary_key(
    sqlite_dialect: SQLiteDialect,
) -> None:
    """SQLiteDialect::createTable removes an auto-increment column's own
    name from the primary_keys list before delegating, since its inline
    'INTEGER PRIMARY KEY AUTOINCREMENT' already declares the table's sole
    primary key -- listing it again would produce a second, invalid
    PRIMARY KEY (...) clause."""
    qwp = sqlite_dialect.create_table(
        if_not_exists=False,
        table="users",
        columns=[Column(name="id", type=TypeEnum.INT, auto_increment=True)],
        primary_keys=["id"],
    )
    assert qwp.query.count("PRIMARY KEY") == 1
    assert "INTEGER PRIMARY KEY AUTOINCREMENT" in qwp.query


def test_sqlite_auto_increment_ignores_declared_type(sqlite_dialect: SQLiteDialect) -> None:
    """SQLiteDialect::buildColumn forces INTEGER PRIMARY KEY AUTOINCREMENT
    unconditionally for an identity column, regardless of the declared
    type -- the old code only did this when the resolved type happened to
    already be 'INTEGER'."""
    col_def = sqlite_dialect._build_column(Column(name="id", type="BIGINT", auto_increment=True))
    assert col_def == '"id" INTEGER PRIMARY KEY AUTOINCREMENT'


def test_sqlite_drop_column_has_no_version_gate() -> None:
    """SQLiteDialect has no buildAlterTableDropColumn override in PHP --
    DROP COLUMN is always emitted regardless of version (unlike
    RENAME COLUMN, which is explicitly version-gated)."""
    old_sqlite = SQLiteDialect(version="3.1.0")
    qwp = old_sqlite._build_alter("t", DropColumn(column="c"))
    assert qwp.query == 'ALTER TABLE "t" DROP COLUMN "c"'
