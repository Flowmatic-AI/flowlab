def test_pg_escape_string_uses_escape_chars(pg_dialect: PostgresqlDialect) -> None:
    """PgSQLDialect doesn't override escapeString -- it configures
    ESCAPE_CHARS on the shared base implementation instead."""
    assert pg_dialect.escape_string("it's") == "'it''s'"
    assert pg_dialect.escape_string("back\\slash") == "'back\\\\slash'"
    assert pg_dialect.escape_string("line1\nline2\ttab") == "'line1\\nline2\\ttab'"
    assert pg_dialect.escape_string("nul\x00byte") == "'nulbyte'"


def test_pg_returning_and_on_conflict_not_overridden_beyond_gating(pg_dialect: PostgresqlDialect) -> None:
    """PgSQLDialect never overrides buildReturning; it must fully inherit
    the base's self.returning gate (an empty-but-non-None returning list
    still renders RETURNING *)."""
    qwp = pg_dialect.insert(table="users", values=[{"name": "a"}], on_conflict=None, returning=[], last_insert_id=None)
    assert "RETURNING *" in qwp.query


def test_sqlite_like_is_case_sensitive_glob_by_default(sqlite_dialect: SQLiteDialect) -> None:
    """SQLiteDialect::buildConditionLike: native SQLite LIKE is
    case-insensitive for ASCII, so the (case-sensitive) default LIKE
    condition is translated to GLOB instead."""
    cond = Condition(condition=ConditionEnum.LIKE, identifier="name", value="foo%bar_baz")
    parts: list[str] = []
    params: list[object] = []
    sqlite_dialect._build_condition(parts, params, cond)
    assert "".join(parts) == '"name" GLOB ?'
    assert params == ["foo*bar?baz"]


