"""Regression tests for the MySQL/PostgreSQL/SQLite dialect subclasses,
covering behavioral gaps found while re-porting them to delegate via
super()/the base dialect's seams instead of reimplementing shared logic.

Each test here maps to a specific PHP source of truth cited in its
docstring -- see Database/Dialects/{MySQLDialect,PgSQLDialect,
SQLiteDialect}.php.
"""

from __future__ import annotations

from flowlab.modules.db.dialects import MySQLDialect, PostgresqlDialect, SQLiteDialect
from flowlab.modules.db.query import Condition
from flowlab.modules.db.query.ddl import Column, DropColumn, ForeignKeyConstraint, UniqueConstraint
from flowlab.modules.db.query.enums import ConditionEnum, TypeEnum


def test_mysql_cast_types_used_for_equals_cast(mysql_dialect: MySQLDialect) -> None:
    """MySQLDialect::CAST_TYPES remaps bool/int/float/string to
    UNSIGNED/SIGNED/DECIMAL/CHAR instead of the generic SQL type names."""
    cond = Condition(condition=ConditionEnum.EQUALS, identifier="n", value=42, cast=True)
    parts: list[str] = []
    params: list[object] = []
    mysql_dialect._build_condition(parts, params, cond)
    result = "".join(parts)
    assert "AS SIGNED)" in result

    cond_str = Condition(condition=ConditionEnum.EQUALS, identifier="s", value="x", cast=True)
    parts2: list[str] = []
    params2: list[object] = []
    mysql_dialect._build_condition(parts2, params2, cond_str)
    assert "AS CHAR)" in "".join(parts2)


def test_mysql_default_value_escaping_uses_escape_chars(mysql_dialect: MySQLDialect) -> None:
    """A string DEFAULT goes through escape_string(), which must wrap in '"'
    and backslash-escape control characters per MySQLDialect::ESCAPE_CHARS,
    not the hand-rolled two-char .replace() chain the old override used."""
    col_def = mysql_dialect._build_column(Column(name="note", type=TypeEnum.STRING, default="a\nb"))
    assert col_def == '`note` VARCHAR(255) DEFAULT "a\\nb"'


def test_mysql_datetime_format_includes_microseconds(mysql_dialect: MySQLDialect) -> None:
    """MySQLDialect::DATETIME_FORMAT is 'Y-m-d H:i:s.u' (with fractional
    seconds) -- the old port's format string omitted the .%f part."""
    from datetime import UTC, datetime

    dt = datetime(2024, 1, 2, 3, 4, 5, 123456, tzinfo=UTC)
    assert mysql_dialect.cast_datetime(dt) == "2024-01-02 03:04:05.123456"


def test_pg_identity_column_prefers_serial_even_on_modern_version() -> None:
    """PgSQLDialect::buildColumn: SERIAL is the preferred form on every
    PostgreSQL version, so an auto-increment column stays SERIAL on 17+ too."""
    pg = PostgresqlDialect(version="17")
    col_def = pg._build_column(Column(name="id", type=TypeEnum.INT, auto_increment=True, not_null=True))
    assert col_def == '"id" SERIAL NOT NULL'


def test_pg_use_serials_disabled_opts_into_identity_on_pg17() -> None:
    """PgSQLDialect::buildColumn: opting out of serials on PostgreSQL >= 17
    delegates to the base column builder, which emits the identity clause."""
    pg = PostgresqlDialect(version="17", options={"use_serials": False})
    col_def = pg._build_column(Column(name="id", type=TypeEnum.INT, auto_increment=True, not_null=True))
    assert "GENERATED BY DEFAULT AS IDENTITY" in col_def
    assert "SERIAL" not in col_def.upper()


def test_pg_use_serials_disabled_still_serial_before_pg17() -> None:
    """The identity clause is gated on the server version first, so opting out
    of serials below 17 changes nothing."""
    pg = PostgresqlDialect(version="16", options={"use_serials": False})
    col_def = pg._build_column(Column(name="id", type="INTEGER", auto_increment=True))
    assert col_def == '"id" SERIAL'


def test_pg_identity_column_falls_back_to_serial_before_pg17() -> None:
    """PgSQLDialect::buildColumn: below PostgreSQL 17, an identity column
    swaps its type for SERIAL/BIGSERIAL instead."""
    pg = PostgresqlDialect(version="16")
    assert pg.generated_by_default_as_identity is False

    int_col = pg._build_column(Column(name="id", type="INTEGER", auto_increment=True))
    assert int_col == '"id" SERIAL'

    bigint_col = pg._build_column(Column(name="id", type="bigint", auto_increment=True))
    assert bigint_col == '"id" bigserial'


def test_pg_serial_column_drops_default() -> None:
    """SERIAL expands to a nextval() default of its own, so carrying the
    caller's default through would produce "multiple default values specified
    for column"."""
    pg = PostgresqlDialect(version="16")
    col = pg._build_column(Column(name="id", type="INTEGER", auto_increment=True, default=5))
    assert col == '"id" SERIAL'


def test_pg_use_serials_option_forces_serial_even_on_pg17() -> None:
    pg = PostgresqlDialect(version="17", options={"use_serials": True})
    col_def = pg._build_column(Column(name="id", type="INTEGER", auto_increment=True))
    assert col_def == '"id" SERIAL'


def test_pg_generated_by_default_as_identity_gate() -> None:
    """PgSQLDialect::generatedByDefaultAsIdentity() gates on PostgreSQL 17+
    (see the README's documented PostgreSQL support matrix), not 10."""
    assert PostgresqlDialect(version="16").generated_by_default_as_identity is False
    assert PostgresqlDialect(version="17").generated_by_default_as_identity is True


